// Функция проверки одного пользователя
export async function checkCriminalActivity(accessToken) {
  const alerts = [];

  await Promise.all(CRIM_GUILDS.map(async (guild) => {
    if (guild.roles.length === 0) return;

    try {
      const res = await fetch(
        `https://discord.com/api/users/@me/guilds/${guild.id}/member`,
        { headers: { Authorization: `Bearer ${accessToken}` } }
      );

      if (res.status === 404) return;
      if (!res.ok) return;

      const member = await res.json();
      const userRoles = member.roles || [];

      const matchedRoles = guild.roles.filter(r => userRoles.includes(r.id));

      if (matchedRoles.length > 0) {
        // Оставляем уникальные названия ролей, чтобы не дублировать их в логах
        const uniqueRoles = [...new Set(matchedRoles.map(r => r.name))];
        
        alerts.push({
          guildName: guild.name,
          guildId: guild.id,
          matchedRoles: uniqueRoles,
        });
      }
    } catch (e) {
      console.error(`Ошибка проверки гильдии ${guild.id}:`, e.message);
    }
  }));

  return alerts;
}
